#!/usr/bin/env python3
"""
One-command pipeline for the ME 306 Problem 16 team project.

    python run_pipeline.py            # full run (validation + NSGA-II ~10 min + selection + figures + tables)
    python run_pipeline.py --quick    # reuse the stored NSGA-II / grid results, redo everything downstream
    python run_pipeline.py --report   # also compile both LaTeX reports (needs pdflatex on PATH)

Every number, table and figure in report/Problem16_Group_Report.pdf is regenerated by this script.
"""
import argparse, os, shutil, subprocess, sys, time

ROOT = os.path.dirname(os.path.abspath(__file__))
CODE = os.path.join(ROOT, "r5_integration", "code")
STEPS_FULL = ["r5_validate.py", "r5_run_all.py", "r5_select.py", "r5_figures.py",
              "r5_make_tables.py", "r5_group_extras.py"]


def run(script):
    t = time.time()
    print(f"\n=== {script} ===", flush=True)
    r = subprocess.run([sys.executable, script], cwd=CODE)
    if r.returncode != 0:
        sys.exit(f"{script} failed (exit {r.returncode})")
    print(f"--- {script} done in {time.time() - t:.0f} s")


def latex(folder, tex):
    if not shutil.which("pdflatex"):
        print("pdflatex not found - skipping report compilation"); return
    for _ in range(2):
        subprocess.run(["pdflatex", "-interaction=nonstopmode", tex], cwd=folder, stdout=subprocess.DEVNULL)
    print("compiled", os.path.join(folder, tex.replace(".tex", ".pdf")))


if __name__ == "__main__":
    ap = argparse.ArgumentParser()
    ap.add_argument("--quick", action="store_true", help="skip r5_run_all.py (reuse stored optimisation results)")
    ap.add_argument("--report", action="store_true", help="compile the LaTeX reports at the end")
    a = ap.parse_args()
    steps = [s for s in STEPS_FULL if not (a.quick and s == "r5_run_all.py")]
    if a.quick and not os.path.exists(os.path.join(ROOT, "r5_integration", "results", "pareto_front_5obj.csv")):
        sys.exit("--quick needs stored results; run without --quick first")
    for s in steps:
        run(s)
    if a.report:
        latex(os.path.join(ROOT, "report"), "Problem16_Group_Report.tex")
        latex(os.path.join(ROOT, "r5_integration", "report"), "R5_Integration_Report.tex")
    print("\nAll done. Results: r5_integration/results/  Figures: r5_integration/figures/")
